"""Draw the S4 signal plot for D1 (Figure: signals) from eval/results/confidence_pilot.csv.

Writes a TikZ picture with two strips, one per signal (top dense score and the model's sufficiency
score), and one dot per pilot question: answerable questions above the line, unanswerable ones below.
Near-miss unanswerable questions that score above at least one answerable question are labelled.
The numbers come straight from the results file, so the figure can be regenerated after any rerun.

Output: d1/images/signal_plot.tex
Usage:  python -m eval.plot_signals
"""
import csv

from src.config import ROOT, load_config

WIDTH = 11.0  # cm of each strip
# label text and anchor (staggered so the two labels do not overlap)
LABELS = {"U03": ("U03 late-payment charge", "north east"), "N02": ("N02 MC appeal", "north west")}
BLUE, RED, ORANGE = "blue!60!black", "red!70!black", "orange!90!black"


def dot(x, y, colour, opacity=""):
    return f"  \\fill[{colour}{opacity}] ({x:.2f},{y:.2f}) circle (2.2pt);"


def strip(rows, col, lo, hi, y, title, ticks):
    """TikZ commands for one strip: axis with ticks above it, and a dot per question."""
    def x(v):
        return (float(v) - lo) / (hi - lo) * WIDTH
    out = [f"  \\node[anchor=east,font=\\sffamily\\scriptsize,align=right] at (-0.2,{y:.2f}) {{{title}}};",
           f"  \\draw[gray!70] (0,{y:.2f}) -- ({WIDTH},{y:.2f});"]
    for t in ticks:
        out.append(f"  \\draw[gray!70] ({x(t):.2f},{y:.2f}) -- ({x(t):.2f},{y + 0.08:.2f});")
        out.append(f"  \\node[font=\\sffamily\\tiny,text=gray!40!black] at ({x(t):.2f},{y + 0.45:.2f}) {{{t}}};")
    lowest_answerable = min(float(r[col]) for r in rows if r["answerable"] == "yes")
    for r in rows:
        v = float(r[col])
        if r["answerable"] == "yes":
            out.append(dot(x(v), y + 0.18, BLUE, ",opacity=0.55"))
            continue
        near = r["qid"] in LABELS and v > lowest_answerable
        out.append(dot(x(v), y - 0.18, ORANGE if near else RED))
        if near and col == "dense_top":
            text, anchor = LABELS[r["qid"]]
            out.append(f"  \\node[font=\\sffamily\\tiny,text=orange!60!black,anchor={anchor},inner sep=1pt] "
                       f"at ({x(v):.2f},{y - 0.26:.2f}) {{{text}}};")
    # questions with the same score overlap, so show how many share each value
    for group, dy in (("yes", 0.18), ("no", -0.18)):
        counts = {}
        for r in rows:
            if r["answerable"] == group:
                counts[float(r[col])] = counts.get(float(r[col]), 0) + 1
        for v, n in counts.items():
            if n > 1 and col == "model_score":
                out.append(f"  \\node[font=\\sffamily\\tiny,anchor=west,inner sep=1pt] at ({x(v) + 0.1:.2f},{y + dy:.2f}) "
                           f"{{$\\times${n}}};")
    return out


def main():
    cfg = load_config()
    with open(cfg["results_dir"] / "confidence_pilot.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    n_ans = sum(r["answerable"] == "yes" for r in rows)
    lines = ["% S4 signal plot (Figure: signals). Generated by eval/plot_signals.py from eval/results/confidence_pilot.csv;",
             "% do not edit by hand. Needs \\usepackage{tikz}.",
             "\\begin{tikzpicture}[font=\\sffamily\\small]"]
    lines += strip(rows, "dense_top", 0.50, 0.80, 1.7, "Top dense score", ["0.50", "0.60", "0.70", "0.80"])
    lines += strip(rows, "model_score", 0, 100, 0.0, "Model sufficiency\\\\score (0--100)", ["0", "50", "100"])
    legend = [(BLUE, f"answerable ({n_ans})"), (RED, f"unanswerable ({len(rows) - n_ans})"),
              (ORANGE, "near-miss, unanswerable")]
    for i, (colour, text) in enumerate(legend):
        y = 1.9 - 0.45 * i
        lines.append(dot(WIDTH + 0.5, y, colour))
        lines.append(f"  \\node[right,font=\\sffamily\\scriptsize] at ({WIDTH + 0.6:.2f},{y:.2f}) {{{text}}};")
    lines.append("\\end{tikzpicture}")
    out = ROOT / "d1" / "images" / "signal_plot.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out} ({len(rows)} questions)")


if __name__ == "__main__":
    main()
